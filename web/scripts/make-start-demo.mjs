// Writes src/pages/startDemo.ts: one sample game (made-up player) for the landing page's replay,
// plus how often the same habit shows up across the sample player's last ten games, the sample player's two most
// played openings as white, and how often the sample rival shows their costliest habit.
// node scripts/make-start-demo.mjs
import { readFileSync, writeFileSync } from "node:fs";

const GAME = "s05";
const TAG = "hanging_piece";
const RIVAL_TAG = "rushed"; // the sample rival's first tip on the Compare page
const reviews = JSON.parse(readFileSync(new URL("../public/sample/reviews.json", import.meta.url))).map((s) => s.review);
const r = reviews.find((v) => v.game.id === GAME);
const g = r.game;
const mine = (w) => (g.color === "white" ? w : 100 - w);
const turn = r.moves.filter((m) => m.mine).sort((a, b) => b.win_loss - a.win_loss)[0];
const i = r.moves.indexOf(turn);
const recent = [...reviews].sort((a, b) => b.game.t - a.game.t).slice(0, 10).reverse();

// Each opening as the results of its games, oldest first ("w", "d" or "l").
function openingsAs(color) {
  const by = new Map();
  for (const v of [...reviews].sort((a, b) => a.game.t - b.game.t)) {
    if (v.game.color !== color) continue;
    const name = v.game.opening.split(":")[0];
    by.set(name, [...(by.get(name) ?? []), v.game.result[0]]);
  }
  return [...by].sort((a, b) => b[1].length - a[1].length).slice(0, 2).map(([name, results]) => ({ name, results }));
}

function rivalHabit() {
  const rival = JSON.parse(readFileSync(new URL("../public/sample/rival-reviews.json", import.meta.url))).map((s) => s.review);
  const last = [...rival].sort((a, b) => b.game.t - a.game.t).slice(0, 30).reverse();
  return { tag: RIVAL_TAG, games: last.map((v) => v.moves.some((m) => m.mine && m.tags.some((t) => t.tag === RIVAL_TAG))) };
}

const out = {
  color: g.color,
  opponent: g.opponent,
  accuracy: Math.round(g.accuracy * 10) / 10,
  oppAccuracy: Math.round(g.opp_accuracy * 10) / 10,
  startFen: r.start_fen,
  startWin: Math.round(mine(r.start_win_white)),
  moves: r.moves.map((m) => ({ san: m.san, uci: m.uci, fen: m.fen, cls: m.class, win: Math.round(mine(m.win_white)) })),
  turn: {
    index: i,
    before: i > 0 ? Math.round(mine(r.moves[i - 1].win_white)) : Math.round(mine(r.start_win_white)),
    after: Math.round(mine(turn.win_white)),
    piece: turn.tags.find((t) => t.tag === TAG)?.detail.piece ?? null,
    square: turn.tags.find((t) => t.tag === TAG)?.detail.square ?? null,
    best: turn.best,
    bestUci: turn.best_uci,
    reply: turn.reply_line[0] ?? null,
    accept: turn.retry?.accept ?? [],
  },
  habit: recent.map((v) => v.moves.some((m) => m.mine && m.tags.some((t) => t.tag === TAG))),
  openings: openingsAs("white"),
  rival: rivalHabit(),
};
writeFileSync(new URL("../src/pages/startDemo.ts", import.meta.url), `// Generated by scripts/make-start-demo.mjs from the sample player (made up). Do not edit.\nexport const DEMO = ${JSON.stringify(out)};\n`);
console.log(out.openings.map((o) => `${o.name} ${o.results.join("")}`).join(", "), `| rival ${out.rival.games.filter(Boolean).length}/${out.rival.games.length}`);
console.log(`${out.moves.length} plies, turn at ${i + 1}: ${turn.san} ${out.turn.before}% -> ${out.turn.after}%, habit ${out.habit.filter(Boolean).length}/10`);
